// NORMALIZE LANGUAGE CODE (MAPS UK TO UA)
const normalizeLangCode = (raw) => {
  if (!raw) return null;
  const upper = raw.toUpperCase();
  if (upper === 'UK' || upper === 'UA') return 'UA';
  return languages.value.some((l) => l.code === upper) ? upper : null;
};

// DETECT INITIAL LANGUAGE FROM URL, LOCAL STORAGE, OR BROWSER
const getInitialLanguage = () => {
  if (typeof window !== 'undefined') {
    const params = new URLSearchParams(window.location.search);
    const urlLangCode = normalizeLangCode(params.get('lang'));
    if (urlLangCode) {
      return languages.value.find((l) => l.code === urlLangCode);
    }
  }

  const savedLangCode = normalizeLangCode(localStorage.getItem('efimovs_lang'));
  if (savedLangCode) {
    return languages.value.find((l) => l.code === savedLangCode);
  }

  if (typeof navigator !== 'undefined') {
    const browserLangCode = normalizeLangCode(navigator.language.slice(0, 2));
    if (browserLangCode) {
      return languages.value.find((l) => l.code === browserLangCode);
    }
  }

  return languages.value[0];
};

