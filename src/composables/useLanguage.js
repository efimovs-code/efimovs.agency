// SYNC SELECTED LANGUAGE WITH STORAGE AND SEO META TAGS
watch(
  currentLang,
  (newLang) => {
    localStorage.setItem('efimovs_lang', newLang.code);

    if (typeof document !== 'undefined') {
      const htmlLang = newLang.code === 'UA' ? 'uk' : newLang.code.toLowerCase();
      document.documentElement.lang = htmlLang;

      const isPortfolio =
        typeof window !== 'undefined' && window.location.pathname === '/portfolio';
      const canonicalUrl = isPortfolio
        ? 'https://efimovs.agency/portfolio'
        : htmlLang === 'en'
          ? 'https://efimovs.agency/'
          : `https://efimovs.agency/?lang=${htmlLang}`;

      const canonicalTag = document.querySelector('link[rel="canonical"]');
      if (canonicalTag) {
        canonicalTag.setAttribute('href', canonicalUrl);
      }

      const ogUrlTag = document.querySelector('meta[property="og:url"]');
      if (ogUrlTag) {
        ogUrlTag.setAttribute('content', canonicalUrl);
      }

      const localizedDesc = seoDescriptions[newLang.code] || seoDescriptions.EN;
      const metaDescTag = document.querySelector('meta[name="description"]');
      if (metaDescTag) {
        metaDescTag.setAttribute('content', localizedDesc);
      }

      const ogDescTag = document.querySelector('meta[property="og:description"]');
      if (ogDescTag) {
        ogDescTag.setAttribute('content', localizedDesc);
      }
    }
  },
  { immediate: true }
);

