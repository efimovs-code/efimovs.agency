import { ref, watch } from 'vue';

// 🌐 Глобальная языковая система
export const languages = ref([
  { code: 'EN', name: 'English', flag: 'us' },
  { code: 'RU', name: 'Русский', flag: 'ru' },
  { code: 'UA', name: 'Українська', flag: 'ua' },
  { code: 'TR', name: 'Türkçe', flag: 'tr' },
  { code: 'DE', name: 'Deutsch', flag: 'de' },
  { code: 'FR', name: 'Français', flag: 'fr' },
  { code: 'ES', name: 'Español', flag: 'es' },
]);

const normalizeLangCode = (raw) => {
  if (!raw) return null;
  const upper = raw.toUpperCase();
  if (upper === 'UK' || upper === 'UA') return 'UA';
  return languages.value.some((l) => l.code === upper) ? upper : null;
};

// ОПТИМИЗАЦИЯ SEO & UX: Умная инициализация языка (сначала проверяем ?lang= из URL для поисковиков)
const getInitialLanguage = () => {
  // 1. Проверяем параметр ?lang= в адресной строке (критично для индексации RU/UA/DE/FR/ES/TR в Google)
  if (typeof window !== 'undefined') {
    const params = new URLSearchParams(window.location.search);
    const urlLangCode = normalizeLangCode(params.get('lang'));
    if (urlLangCode) {
      return languages.value.find((l) => l.code === urlLangCode);
    }
  }

  // 2. Проверяем, сохранял ли пользователь язык ранее
  const savedLangCode = normalizeLangCode(localStorage.getItem('efimovs_lang'));
  if (savedLangCode) {
    return languages.value.find((l) => l.code === savedLangCode);
  }

  // 3. Если нет, пытаемся определить язык браузера (fallback)
  if (typeof navigator !== 'undefined') {
    const browserLangCode = normalizeLangCode(navigator.language.slice(0, 2));
    if (browserLangCode) {
      return languages.value.find((l) => l.code === browserLangCode);
    }
  }

  // 4. По умолчанию Английский
  return languages.value[0];
};

export const currentLang = ref(getInitialLanguage());

// ОПТИМИЗАЦИЯ SEO & ПАМЯТИ: Следим за сменой языка
watch(currentLang, (newLang) => {
  // Сохраняем выбор, чтобы после F5 язык не сбрасывался
  localStorage.setItem('efimovs_lang', newLang.code);

  // Динамически меняем атрибут <html> для SEO
  if (typeof document !== 'undefined') {
    const htmlLang = newLang.code === 'UA' ? 'uk' : newLang.code.toLowerCase();
    document.documentElement.lang = htmlLang;
  }
}, { immediate: true });

